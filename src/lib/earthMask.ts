const px = (lon: number) => ((lon + 180) / 360) * W
const py = (lat: number) => ((90 - lat) / 180) * H

function blobs(list: number[][]): Float32Array {
  const c = document.createElement('canvas')
  c.width = W; c.height = H
  const g = c.getContext('2d')!
  g.fillStyle = '#000'; g.fillRect(0, 0, W, H)
  g.globalCompositeOperation = 'lighter'
  for (const [lon, lat, rx, ry, k] of list) {
    g.save()
    g.translate(px(lon), py(lat))
    g.scale((rx / 360) * W, (ry / 180) * H)
    const gr = g.createRadialGradient(0, 0, 0, 0, 0, 1)
    gr.addColorStop(0, `rgba(255,255,255,${k})`)
    gr.addColorStop(1, 'rgba(255,255,255,0)')
    g.fillStyle = gr
    g.beginPath(); g.arc(0, 0, 1, 0, Math.PI * 2); g.fill()
    g.restore()
  }
  return readRed(g)
}

function readRed(g: CanvasRenderingContext2D): Float32Array {
  const d = g.getImageData(0, 0, W, H).data
  const out = new Float32Array(W * H)
  for (let i = 0; i < out.length; i++) out[i] = d[i * 4] / 255
  return out
}

/** Blur de caixa separável (wrap em x). */
function boxBlur(a: Float32Array, r: number, passes: number) {
  const tmp = new Float32Array(a.length)
  for (let p = 0; p < passes; p++) {
    for (let y = 0; y < H; y++) {
      let s = 0
      for (let x = -r; x <= r; x++) s += a[y * W + ((x + W) % W)]
      for (let x = 0; x < W; x++) {
        tmp[y * W + x] = s / (2 * r + 1)
        s += a[y * W + ((x + r + 1) % W)] - a[y * W + ((x - r + W) % W)]
      }
    }
    for (let x = 0; x < W; x++) {
      let s = 0
      for (let y = -r; y <= r; y++) s += tmp[Math.min(H - 1, Math.max(0, y)) * W + x]
      for (let y = 0; y < H; y++) {
        a[y * W + x] = s / (2 * r + 1)
        s += tmp[Math.min(H - 1, y + r + 1) * W + x] - tmp[Math.max(0, y - r) * W + x]
      }
    }
  }
}

function build(): CanvasTexture {
  // terra
  const c = document.createElement('canvas')
  c.width = W; c.height = H
  const g = c.getContext('2d')!
  g.fillStyle = '#000'; g.fillRect(0, 0, W, H)
  g.fillStyle = '#fff'
  for (const poly of LAND) {
    g.beginPath()
    for (let i = 0; i < poly.length; i += 2) {
      const x = px(poly[i]), y = py(poly[i + 1])
      if (i === 0) g.moveTo(x, y); else g.lineTo(x, y)
    }
    g.closePath(); g.fill()
  }
  const land = readRed(g)
  boxBlur(land, 3, 2)

  const elev = blobs(ELEV)
  const arid = blobs(ARID)
  boxBlur(elev, 2, 1)

  const out = document.createElement('canvas')
  out.width = W; out.height = H
  const og = out.getContext('2d')!
  const img = og.createImageData(W, H)
  for (let i = 0; i < W * H; i++) {
    img.data[i * 4] = Math.min(255, land[i] * 255)
    img.data[i * 4 + 1] = Math.min(255, elev[i] * 255)
    img.data[i * 4 + 2] = Math.min(255, arid[i] * 255)
    img.data[i * 4 + 3] = 255
  }
  og.putImageData(img, 0, 0)

  const tex = new CanvasTexture(out)
  tex.wrapS = RepeatWrapping
  tex.wrapT = ClampToEdgeWrapping
  tex.minFilter = LinearMipmapLinearFilter
  tex.magFilter = LinearFilter
  tex.anisotropy = 4
  tex.generateMipmaps = true
  return tex
}

let tex: CanvasTexture | null = null
let refs = 0
export function acquireEarthMask(): CanvasTexture {
  if (!tex) tex = build()
  refs++
  return tex
}
export function releaseEarthMask() {
  refs = Math.max(0, refs - 1)
  if (refs === 0 && tex) { tex.dispose(); tex = null }
}
